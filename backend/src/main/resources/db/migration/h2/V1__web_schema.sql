-- Web service schema, H2 version (desktop application and fast tests).
-- Keep in sync with db/migration/mysql/V1__web_schema.sql. H2 compares strings case- and accent-sensitively.

CREATE TABLE users (
    id           VARCHAR(255) NOT NULL,
    username     VARCHAR(255),
    email        VARCHAR(320),
    created_at   TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) NOT NULL,
    last_seen_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

CREATE TABLE scans (
    id                  CHAR(36) NOT NULL,
    user_id             VARCHAR(255) NOT NULL,
    base_domain         VARCHAR(253) NOT NULL,
    base_domain_unicode VARCHAR(253) NOT NULL,
    status              VARCHAR(16) NOT NULL,
    force_refresh       BOOLEAN DEFAULT FALSE NOT NULL,
    total_domains       INT DEFAULT 0 NOT NULL,
    checked_domains     INT DEFAULT 0 NOT NULL,
    worker_id           VARCHAR(100),
    heartbeat_at        TIMESTAMP(3),
    created_at          TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) NOT NULL,
    started_at          TIMESTAMP(3),
    finished_at         TIMESTAMP(3),
    error               VARCHAR(500),
    CONSTRAINT pk_scans PRIMARY KEY (id),
    CONSTRAINT fk_scans_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_scans_user_created ON scans (user_id, created_at);
CREATE INDEX idx_scans_status_created ON scans (status, created_at);

CREATE TABLE domain_checks (
    domain         VARCHAR(253) NOT NULL,
    domain_unicode VARCHAR(253) NOT NULL,
    status         VARCHAR(16) NOT NULL,
    http_code      INT NOT NULL,
    tls_status     VARCHAR(20) NOT NULL,
    title          VARCHAR(500),
    language       VARCHAR(32),
    description    VARCHAR(1000),
    homepage_text  VARCHAR(1000),
    http_headers   CLOB,
    screenshot_key VARCHAR(255),
    checked_at     TIMESTAMP(3) NOT NULL,
    CONSTRAINT pk_domain_checks PRIMARY KEY (domain)
);
CREATE INDEX idx_domain_checks_checked_at ON domain_checks (checked_at);

CREATE TABLE scan_results (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    scan_id        CHAR(36) NOT NULL,
    domain         VARCHAR(253) NOT NULL,
    domain_unicode VARCHAR(253) NOT NULL,
    status         VARCHAR(16) NOT NULL,
    http_code      INT NOT NULL,
    tls_status     VARCHAR(20) NOT NULL,
    title          VARCHAR(500),
    language       VARCHAR(32),
    description    VARCHAR(1000),
    homepage_text  VARCHAR(1000),
    http_headers   CLOB,
    screenshot_key VARCHAR(255),
    checked_at     TIMESTAMP(3) NOT NULL,
    CONSTRAINT pk_scan_results PRIMARY KEY (id),
    CONSTRAINT uk_scan_results_domain UNIQUE (scan_id, domain),
    CONSTRAINT fk_scan_results_scan FOREIGN KEY (scan_id) REFERENCES scans (id) ON DELETE CASCADE
);
